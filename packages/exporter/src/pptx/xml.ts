/**
 * **XML 글자를 만드는 자리 하나.**
 *
 * HTML 쪽은 React가 이스케이프하므로 escape 함수를 따로 두지 않는다(`page.tsx`의
 * 머리말 — *"우리가 따로 escape 함수를 쓰면 React의 것과 규칙이 갈린다"*). **OOXML에는
 * React가 없다.** 그래서 여기 두고, **자리를 하나로 둔다** — 파트마다 따로
 * 이스케이프하면 한 자리만 빠뜨렸을 때 그 pptx는 *"열리지 않는 파일"*이 된다.
 *
 * ---
 *
 * # 이스케이프보다 먼저 하는 것이 있다 — **XML 1.0이 못 담는 글자를 걷는다**
 *
 * 이스케이프는 `&`·`<`·`>`·`"`를 다루지만 **제어 문자는 이스케이프로 담기지 않는다.**
 * XML 1.0의 `Char`은 `#x9`·`#xA`·`#xD`와 `#x20` 이상만 허용하므로, 문자 참조(`&#1;`)로
 * 써도 규격 위반이다. 그런 바이트가 pptx에 들어가는 길이 실제로 있다 — **코멘트 본문은
 * 사람이 붙여넣는 글자이고** 편집 파이프라인이 제어 문자를 막지 않는다.
 *
 * **막지 않고 걷는다.** 던지면 코멘트 하나 때문에 설계서 전체가 안 나오고, 그대로 두면
 * **눈으로는 그럴듯한데 안 열리는 파일**이 남에게 전달된다.
 *
 * **짝 잃은 서로게이트도 걷는다.** JS 문자열은 그것을 담을 수 있지만 UTF-8로 인코딩할 수
 * 없어서, 남겨 두면 `strToU8`이 `U+FFFD`를 흘려 **바이트가 조용히 달라진다.**
 */

/**
 * XML 1.0이 담을 수 없는 글자. 위 머리말이 근거다.
 *
 * **글자를 이스케이프로 적는다** — 이 저장소는 소스에 날 제어 바이트를 넣지 않는다.
 * 갈래는 셋이다: 제어 문자(`#x9`·`#xA`·`#xD`를 뺀 나머지) · 규격이 못 박은 비문자
 * (`#xFFFE`·`#xFFFF`) · **짝 잃은 서로게이트**(앞·뒤 둘 다).
 */
const FORBIDDEN =
  /[\u0000-\u0008\u000B\u000C\u000E-\u001F\uFFFE\uFFFF]|[\uD800-\uDBFF](?![\uDC00-\uDFFF])|(?<![\uD800-\uDBFF])[\uDC00-\uDFFF]/g

/**
 * 요소의 **텍스트**. `<a:t>` 안에 들어가는 것이 전부 이것을 지난다.
 *
 * **`>`도 이스케이프한다.** 규격은 `]]>` 안에서만 요구하지만 세 글자를 한 규칙으로 두면
 * *"어느 자리에서만 필요한가"*를 판단할 일이 없어진다.
 */
export function xmlText(value: string): string {
  return value.replace(FORBIDDEN, '').replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
}

/** 속성 값. 텍스트가 거르는 것에 더해 따옴표 둘을 거른다 — **속성은 `"`로 감싼다.** */
export function xmlAttr(value: string): string {
  return xmlText(value).replaceAll('"', '&quot;').replaceAll("'", '&apos;')
}

/**
 * 모든 파트의 첫 줄.
 *
 * **`standalone="yes"`까지 쓴다** — PowerPoint가 내는 파일이 그 모양이고(참조 pptx에서
 * 쟀다), 규격이 요구하지 않아도 받는 쪽이 흔히 보는 형태에서 벗어날 이유가 없다.
 */
export const XML_DECL = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
