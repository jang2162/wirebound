/**
 * **값을 `<script>` 안에 실어도 되는 JSON 리터럴로 만든다.**
 *
 * 이 함수를 쓰는 것은 번들이다 — `runtime.js`가 읽을 페이지 JSON 을 `<script>`에 심는다(`bundle/index.ts` →
 * `shellScripts`). **규칙을 문서의 스니펫으로 두지 않고 함수로 두는 것은 스니펫은 복사되고
 * 어떤 검사도 지키지 않기 때문**이다.
 *
 * > U+2028만 이스케이프하는 스니펫은 **실제로 깨지는 `</script>`를 그대로 통과시킨다.**
 * > 그 코드를 그대로 쓰면 스크립트가 끊기고 뒤따르는 글자가 마크업이 된다 — 재현과 값은
 * > `test/script-json.test.ts`가 든다. **문서의 문장은 어떤 검사도 지키지 않는데 그것이
 * > 실행되는 코드가 된다.**
 *
 * ---
 *
 * ## 무엇이 왜 위험한가 — **HTML 파서는 문자열 안을 보지 않는다**
 *
 * `<script>`는 **raw text 요소**다. 파서는 그 안에서 자바스크립트를 이해하지 않고 **종료
 * 태그만 찾는다.** 그래서 데이터 안의 `</script>`는 *"문자열 안이니 괜찮다"*가 아니라
 * **그 자리에서 스크립트를 끝낸다.** 끝난 뒤의 글자는 자바스크립트가 아니라 **마크업**으로
 * 읽히므로, `</script><img src=x onerror=…>`는 이미지 하나와 그 핸들러가 된다.
 *
 * 실측(jsdom에 넣어 쟀다): `JSON.stringify`만 쓴 리터럴을 `<script>`에 넣으면 그 문서에
 * `img`가 하나 생기고 `onerror`가 붙는다. `<`를 이스케이프하면 `img`가 0개다.
 *
 * ## 그래서 `<` 하나를 막는다
 *
 * `<`는 **JSON에서 `<`와 같은 값**이므로 `JSON.parse`가 원래 문자열을 그대로 돌려준다
 * (케이스가 왕복을 잰다). `<` 하나를 막으면 `</script>`뿐 아니라 `<script`와 `<!--`도 함께
 * 닫힌다 — 셋 다 파서가 raw text 안에서 뜻을 갖는 자리다.
 *
 * **`&`는 이스케이프하지 않는다.** raw text 요소 안에서는 문자 참조가 **해석되지 않는다** —
 * 실측했다: `&amp;`를 넣으면 `textContent`가 `&amp;` 그대로다. 바꾸면 오히려 값이 달라진다.
 *
 * **U+2028·U+2029도 이스케이프하지 않는다.** **ES2019가 그 둘을 문자열 리터럴에서
 * 합법으로 만들었다** — 실측했다: 날 U+2028을 넣은 리터럴이 그대로 파싱되고 가운데 코드가
 * `2028`로 남는다. U+2028만 막는 스니펫은 **막을 필요가 없는 것을 막고 막아야 하는 것을
 * 놓친다.**
 *
 * > **이것이 *"문서에서 U+2028을 금지하지 않는다"*는 판정과 어긋나지 않는다.** 그 판정은
 * > 사용자가 적은 글자를 우리가 줄이지 않겠다는 것이고, 여기는 **우리가 만드는 자리**다.
 * > 다만 지금은 여기서도 할 일이 없다는 것이 위 실측의 결론이다.
 */
export function scriptJson(value: unknown): string {
  const json = JSON.stringify(value)
  if (json === undefined) {
    // `undefined`·함수·심볼은 JSON이 아니다. 조용히 `null`로 바꾸면 **부르는 쪽의 실수가
    // 값의 변화로 위장된다** — 번들에 실릴 데이터라 그 위장이 오래 산다.
    throw new TypeError('JSON으로 만들 수 없는 값입니다')
  }
  return json.replace(/</g, '\\u003c')
}
