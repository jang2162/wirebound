/**
 * **사람이 지은 글을 문장 · 표 · 고르개에 넣을 때 방향을 격리한다** — 사용자 이름 · 이메일 · 초대 링크 이름 · 프로젝트 이름(리뷰
 * `docs/superpowers/plans/2026-11-01-rv-ad-report.md` M1).
 *
 * 이름에 방향 제어 글자(U+202E 등)가 들면 그 뒤의 글까지 뒤집힌다 — 비활성화 확인 상자의 «…(이메일) 계정을 비활성화합니다» 가 거꾸로 서고,
 * 끝을 닫은 이름은 다른 사람의 이름(«박퇴사»)과 같은 글로 보였다. 그래서 둘을 한다.
 *
 * - **FSI(U+2068) … PDI(U+2069)로 감싼다** — 감싼 안의 방향이 밖으로 새지 않는다. 글 노드 하나로 남아 `<option>` · 템플릿 문장에도 쓴다
 *   (`<bdi>` 는 요소라 `<option>` 글과 한 문자열 문장에 못 든다 — 구조 트리의 별칭은 `<bdi>` 다).
 * - **안의 방향 내장 · 덮어쓰기 · 격리 글자(U+202A – U+202E · U+2066 – U+2069)를 걷는다** — 짝 없는 PDI 가 우리의 FSI 를 먼저 닫으면 그 뒤
 *   글자가 격리 밖으로 샌다. 덮어쓰기 글자도 걷어, 이미 든 이름(서버가 막기 전의 행)이 남의 이름처럼 보이지 않는다. 방향 표지(U+200E ·
 *   U+200F · U+061C)는 둔다 — 오른쪽에서 쓰는 이름이 제 차례를 잡는 데 쓴다.
 *
 * 서버는 새 이름에서 이 글자들을 거절한다(`apps/api/src/auth/display-name.ts`). 이 겹은 이미 든 행과 서버가 안 보는 글(초대 링크 이름 밖의 것)을 막는다.
 *
 * **접근 이름 · `title` 에는 쓰지 않는다**(행동 메뉴의 «… 더 보기» 등) — 글의 흐름 속에 그려지지 않고, 그 이름으로 찾는 케이스가 많다.
 */
const EMBEDDING = /[\u202A-\u202E\u2066-\u2069]/g

export function isolate(text: string): string {
  return `\u2068${text.replace(EMBEDDING, '')}\u2069`
}
