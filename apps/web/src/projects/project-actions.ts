/**
 * 프로젝트에 무엇을 할 수 있는지 판정하는 곳(P2b-5 D3). **앱의 첫 역할 분기다.**
 * 화면은 이 결과로 `수정`·`삭제` 버튼을 감추거나 비활성한다 — 눌러 봐야 실패할 버튼을
 * 활성으로 두지 않는다(`tree/tree-actions.ts`·`edit/structure-actions.ts`와 같은 정신).
 *
 * **순수 함수이고 React·DOM·`fetch`를 모른다.** 판정이 컴포넌트 안에 흩어지면 케이스가
 * 화면을 지나야만 재지고, 목록의 각 항목이 자기 조건을 갖게 된다.
 *
 * **판정이 한 자리여야 하는 이유는 셀 수 있는 것이다.** P2b-4 **계획서**가
 * *"`ProjectDetail.role`을 읽는 자리가 0건"*을 근거로 그 단계에서 역할 분기를 만들지 않기로
 * 했다(`2026-08-09-p2b4-menu-page-crud.md`. **앞 판은 이 출처를 "이월 문서"로 적었는데
 * 그 문서에는 그 문장이 없다** — P2b-5 Task 7에서 훑다가 찾았다). 그 수가 늘어나면 그 판단이
 * 어디서 깨지는지 알 수 없게 되므로, **역할을 읽는 곳을 이 함수의 호출부 하나로 모은다.**
 *
 * **그 수를 이 주석이 들고 있지 않다 — `test/role-access.test.ts`가 센다.** 소스를 훑어
 * **주석을 걷고** `.role`을 읽는 코드가 이 함수의 호출부 하나뿐인지 확인한다.
 *
 * > **세는 문장을 주석에 두면 자기 자신을 센다.** 이 자리에서 두 번 그랬다 — 처음에는
 * > `apps/web/src` 전체로 세라고 적어 그 문장이 세어졌고, *"한 파일로 좁혀라"*로 고쳤더니
 * > **좁힌 그 파일 안의 주석**이 세어졌다(리뷰 V3·W3). **범위를 좁히는 것으로는 안 닫힌다** —
 * > 세는 대상 안에 그 문장이 있는 한 같은 일이 난다. 실행으로 재면 낡지 않는다.
 *
 * **던지지 않는 것이 이 파일의 계약이다.** `tree/tree-actions.ts`와 같은 근거다 — 이 판정은
 * 목록을 그리는 중에 불리는데 **목록은 오류 경계 밖이다**(`apps/web/src` 전체에서 경계는
 * 캔버스의 `CanvasBoundary` 하나뿐이라고 P2b-4가 셌다). 그래서 모르는 값에도 답을 낸다.
 *
 * **서버가 내는 것**(api 하네스, `apps/api/test/`에 임시 파일을 두고 재고 지웠다.
 * 계획서의 **재라 #6**이 이것으로 닫힌다):
 *
 * ```
 * editor 멤버  PATCH /projects/:id → 403 {"code":"forbidden","message":"이 작업을 수행할 권한이 없습니다"}
 * editor 멤버  DELETE               → 403 (코드·문장 같음)
 * viewer 멤버  PATCH                → 403 (코드·문장 같음)
 * viewer 멤버  DELETE               → 403 (코드·문장 같음)
 * 멤버가 아닌 사용자 PATCH·DELETE   → 404 {"code":"not-found","message":"프로젝트를 찾을 수 없습니다"}
 * 없는 프로젝트 id  PATCH           → 404 (코드·문장 같음 — 비멤버와 구분되지 않는다)
 * 로그인하지 않은 호출 PATCH        → 401 {"code":"unauthenticated","message":"로그인이 필요합니다"}
 * ```
 *
 * **설계 §10이 문서로 적은 것과 잰 것이 일치한다** — 멤버지만 역할이 모자라면 403,
 * 멤버가 아니면 404다. **비멤버와 "없는 프로젝트"가 같은 코드·문장인 것도 함께 쟀다**(§10이
 * 존재를 숨기려는 목적 그대로다). 그러므로 이 판정이 막는 것은 **403이 될 요청 하나**이고,
 * 404 쪽은 애초에 목록에 그 프로젝트가 실려 오지 않으므로 판정이 닿는 자리가 아니다.
 */
import type { ProjectRole } from '../api/types'

/** 지금 이 프로젝트에 할 수 있는 조작. 화면은 이것으로 버튼을 감추거나 비활성한다. */
export interface ProjectAbilities {
  /** 이름·슬러그·설명 수정. 서버는 셋을 한 `PATCH`로 받는다(README). */
  rename: boolean
  remove: boolean
  /**
   * 프로젝트가 쓸 테마를 고를 수 있는가(`PUT /:projectId/theme` — P4b-3 D2).
   *
   * **테마는 페이지·메뉴와 등급이 다르다** — editor도 페이지를 고치지만 테마는 owner
   * 전용이다(§10·§6.10). 이 한 번의 호출이 그 프로젝트의 **모든 화면**을 바꾸기 때문이다.
   *
   * 위 둘과 값이 같은데도 필드를 따로 두는 이유는 `rename`·`remove`가 그런 것과 같다 —
   * 서버가 셋을 각각 다른 라우트로 받는다.
   */
  chooseTheme: boolean
  /**
   * 테마 **문서를 고칠** 수 있는가(`POST .../themes` · `PUT .../themes/:themeId` — P4c-2 D1).
   *
   * **`chooseTheme`과 값이 같은데도 따로 두는 이유는 `rename`·`remove`가 그런 것과 같다** —
   * 서버가 둘을 다른 라우트로 받는다. 그리고 둘은 **다른 질문**이다: 고르기는
   * *"이 프로젝트가 무엇을 입을까"*이고 편집은 *"그 옷을 고쳐도 되는가"*다. 오늘 둘 다
   * owner인 것은 §10의 관측이지 하나로 합쳐도 된다는 뜻이 아니다.
   *
   * **읽기는 이것으로 막지 않는다.** `GET .../themes/:themeId`는 viewer 게이트이고
   * (`apps/api/src/routes/themes.ts`), 화면은 owner가 아닌 사람에게 **읽기 전용**으로
   * 보여 준다 — 못 들어오게 하면 *"무엇이 적용돼 있는지"*조차 못 본다.
   */
  editTheme: boolean
}

/** 아무것도 못 하는 상태. 역할을 모르거나 계약 밖 값일 때의 답이다. */
const NOTHING: ProjectAbilities = {
  rename: false,
  remove: false,
  chooseTheme: false,
  editTheme: false,
}

/**
 * `role`이 `owner`일 때만 열린다.
 *
 * **`role === 'owner'` 하나로 가르는 것이 요점이다.** 역할별 표를 두면 서버가 역할을 더할
 * 때 그 칸을 채우게 되고, 채우는 사람이 열어 두면 조용히 열린다. 비교로 두면 **모르는
 * 값은 자동으로 닫힌다** — 새 역할이 진짜로 owner급이면 그때 이 조건을 넓히는 커밋이
 * 남는다.
 *
 * `role`의 타입이 `ProjectRole`이라고 해서 런타임 값이 그 셋 중 하나라는 보증은 없다.
 * 그 값은 서버 응답에서 오고, `api/http-client.ts`의 `SHAPES.projectDetail`은 `role`을 보지
 * 않는다(`id`·`name`만 본다). `'admin'`·`'Owner'`·`''`가 그대로 여기까지 올 수 있고,
 * 전부 `NOTHING`이 된다(테스트의 `계약에 없는 역할 문자열은 아무것도 열지 않는다`).
 *
 * **`rename`과 `remove`가 같은 조건인데도 필드를 둘로 두는 이유:** 서버가 둘을 각각
 * `PATCH`·`DELETE`로 받는다. 지금 값이 같은 것은 **오늘의 관측**이지 하나로 합쳐도 된다는
 * 뜻이 아니다 — 합치면 한쪽만 열리는 역할이 생길 때 부르는 쪽을 전부 고쳐야 한다.
 *
 * **화면이 두 버튼을 따로 그린다** — `routes/project-list.tsx`의 `ProjectRow`가
 * `abilities.rename`·`abilities.remove`를 각각 본다(Task 5·6이 만들었다).
 *
 * **그 배선은 케이스가 지킨다 — 앞 판의 *"닫는 케이스를 만들지 못했다"*는 거짓이었다**(리뷰 W5).
 * 오늘 서버에 한쪽만 열리는 역할이 없어 이 함수가 두 필드에 늘 같은 값을 내는 것은 맞지만,
 * **이 함수를 주입해 값을 갈라 놓으면 배선이 드러난다.**
 * `test/routes/project-abilities-wiring.test.tsx`가 `vi.mock`으로 그것을 한다 — 두 배선을
 * 맞바꾸면 **3 사망**이고, 앞 웨이브에 0 사망이던 변이(*"삭제 버튼이 `remove` 대신 `rename`을
 * 본다"*)도 이제 **3 사망**이다.
 *
 * > **"못 만든다"는 문장은 다음 사람이 시도하지 않게 만든다.** 못 만든 것은 그 방법으로
 * > 못 만든 것이고, 여기서는 **판정을 주입하는 방법**이 있었다.
 *
 * > 이 문단은 두 번 갈렸다. 웨이브 1이 *"화면이 두 버튼을 따로 그린다"*를 **현재형**으로 적었고
 * > 그때는 화면이 없어 거짓이었다(리뷰 F4). 그래서 *"아직 없다 — Task 5·6이 만든다"*로 고쳤는데
 * > **웨이브 2가 그것을 만들면서 그쪽이 다시 거짓이 됐다.** *"아직 없다"*류는 **고친 사람이
 * > 만들려는 바로 그것 때문에 낡는다** — 쓸 때 무엇이 갱신하게 만드는지를 함께 적어야 하고,
 * > 여기서는 그 트리거가 같은 브랜치 안에 있었다.
 */
export function projectAbilities(role: ProjectRole | undefined): ProjectAbilities {
  if (role !== 'owner') return NOTHING
  return { rename: true, remove: true, chooseTheme: true, editTheme: true }
}
