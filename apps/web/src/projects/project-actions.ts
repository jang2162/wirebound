/**
 * 프로젝트에 무엇을 할 수 있는지 판정하는 곳(P2b-5 D3). **앱의 첫 역할 분기다.**
 * 화면은 이 결과로 `수정`·`삭제` 버튼을 감추거나 비활성한다 — 눌러 봐야 실패할 버튼을
 * 활성으로 두지 않는다(`tree/tree-actions.ts`·`edit/structure-actions.ts`와 같은 정신).
 *
 * **순수 함수이고 React·DOM·`fetch`를 모른다.** 판정이 컴포넌트 안에 흩어지면 케이스가
 * 화면을 지나야만 재지고, 목록의 각 항목이 자기 조건을 갖게 된다.
 *
 * **판정이 한 자리여야 하는 이유는 셀 수 있는 것이다.** P2b-4 이월이 *"`apps/web/src`에서
 * `.role`을 읽는 자리 0건"*을 근거로 여러 판단을 세웠다. 그 수가 늘어나면 그 판단들이
 * 어디서 깨지는지 알 수 없게 되므로, **역할을 읽는 곳을 이 함수의 호출부 하나로 모은다.**
 *
 * **실측(`rg -n "\.role\b" apps/web/src`)**: P2b-5 웨이브 1을 끝낸 지금 **코드에서 읽는 자리는
 * 0건**이다 — 이 함수를 부르는 자리가 아직 없기 때문이다(웨이브 1은 화면을 만들지 않는다).
 * **그 `rg`가 내는 히트는 지금 이 머리말 주석뿐이다** — 세는 사람이 그것을 코드로 읽지
 * 않도록 적어 둔다(수를 적지 않는 것은 이 문단을 손댈 때마다 그 수가 바뀌기 때문이다.
 * 실제로 한 번 틀렸다). **계획서 D3이 기대한 "1"은 목록 화면이 이 함수를 부르는 웨이브 2에서 참이
 * 된다.** 그때 다시 세어 이 문단을 갈아 끼워라 — 그리고 P2b-4 이월의 *"`.role`을 읽는 자리
 * 0건"*이 거짓이 되므로 그 문서도 함께 고쳐라(계획서 Task 7 Step 2가 그 자리다).
 *
 * **던지지 않는 것이 이 파일의 계약이다.** `tree/tree-actions.ts`와 같은 근거다 — 이 판정은
 * 목록을 그리는 중에 불리는데 **목록은 오류 경계 밖이다**(`apps/web/src` 전체에서 경계는
 * 캔버스의 `CanvasBoundary` 하나뿐이라고 P2b-4가 셌다). 그래서 모르는 값에도 답을 낸다.
 *
 * **서버가 내는 것**(api 하네스, `apps/api/test/`에 임시 파일을 두고 재고 지웠다.
 * 계획서의 **재라 #6**이 이것으로 닫힌다):
 *
 * ```
 * editor 멤버  PATCH /projects/:id → 403 {"code":"forbidden","message":"이 작업을 수행할 권한이 없습니다"}
 * editor 멤버  DELETE               → 403 (코드·문장 같음)
 * viewer 멤버  PATCH                → 403 (코드·문장 같음)
 * viewer 멤버  DELETE               → 403 (코드·문장 같음)
 * 멤버가 아닌 사용자 PATCH·DELETE   → 404 {"code":"not-found","message":"프로젝트를 찾을 수 없습니다"}
 * 없는 프로젝트 id  PATCH           → 404 (코드·문장 같음 — 비멤버와 구분되지 않는다)
 * 로그인하지 않은 호출 PATCH        → 401 {"code":"unauthenticated","message":"로그인이 필요합니다"}
 * ```
 *
 * **설계 §10이 문서로 적은 것과 잰 것이 일치한다** — 멤버지만 역할이 모자라면 403,
 * 멤버가 아니면 404다. **비멤버와 "없는 프로젝트"가 같은 코드·문장인 것도 함께 쟀다**(§10이
 * 존재를 숨기려는 목적 그대로다). 그러므로 이 판정이 막는 것은 **403이 될 요청 하나**이고,
 * 404 쪽은 애초에 목록에 그 프로젝트가 실려 오지 않으므로 판정이 닿는 자리가 아니다.
 */
import type { ProjectRole } from '../api/types'

/** 지금 이 프로젝트에 할 수 있는 조작. 화면은 이것으로 버튼을 감추거나 비활성한다. */
export interface ProjectAbilities {
  /** 이름·슬러그·설명 수정. 서버는 셋을 한 `PATCH`로 받는다(README). */
  rename: boolean
  remove: boolean
}

/** 아무것도 못 하는 상태. 역할을 모르거나 계약 밖 값일 때의 답이다. */
const NOTHING: ProjectAbilities = { rename: false, remove: false }

/**
 * `role`이 `owner`일 때만 열린다.
 *
 * **`role === 'owner'` 하나로 가르는 것이 요점이다.** 역할별 표를 두면 서버가 역할을 더할
 * 때 그 칸을 채우게 되고, 채우는 사람이 열어 두면 조용히 열린다. 비교로 두면 **모르는
 * 값은 자동으로 닫힌다** — 새 역할이 진짜로 owner급이면 그때 이 조건을 넓히는 커밋이
 * 남는다.
 *
 * `role`의 타입이 `ProjectRole`이라고 해서 런타임 값이 그 셋 중 하나라는 보증은 없다.
 * 그 값은 서버 응답에서 오고, `api/http-client.ts`의 `SHAPES.projectDetail`은 `role`을 보지
 * 않는다(`id`·`name`만 본다). `'admin'`·`'Owner'`·`''`가 그대로 여기까지 올 수 있고,
 * 전부 `NOTHING`이 된다(테스트의 `계약에 없는 역할 문자열은 아무것도 열지 않는다`).
 *
 * **`rename`과 `remove`가 같은 조건인데도 필드를 둘로 두는 이유:** 서버가 둘을 각각
 * `PATCH`·`DELETE`로 받고 화면이 두 버튼을 따로 그린다. 지금 값이 같은 것은 **오늘의
 * 관측**이지 하나로 합쳐도 된다는 뜻이 아니다 — 합치면 한쪽만 열리는 역할이 생길 때
 * 부르는 쪽을 전부 고쳐야 한다.
 */
export function projectAbilities(role: ProjectRole | undefined): ProjectAbilities {
  if (role !== 'owner') return NOTHING
  return { rename: true, remove: true }
}
