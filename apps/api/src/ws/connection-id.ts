/**
 * WebSocket 연결 id 를 짓는 자리. **무작위다 — 카운터가 아니다.**
 *
 * 모듈 카운터(`wsc_1`, `wsc_2` …)는 `db/tx.ts`의 SAVEPOINT 이름처럼 프로세스 안에서 안 겹치고 로그를
 * 읽기 쉽다. **그러나 여기서는 «프로세스 안에서»로 모자란다:** 웹은 게시를 같은 키로 다시 보낼 때
 * **첫 보내기의** 연결 id 를 싣는데(`apps/web/src/panels/comment-panel.tsx`의 `submit`), 그 사이 api 가
 * 다시 뜨면 카운터가 `wsc_1`부터 다시 매겨져 **그 옛 id 를 남의 새 연결이 받는다.** 그러면(Chrome 에서
 * 게시 중 api 를 죽였다 띄워 잰다) 앨리스의 «다시 확인»이 앨리스의 옛 id 를 받은 **캐럴을 방송에서 뺀다** —
 * 캐럴의 캔버스에 번호가 안 서고, 다음 프레임이 갭이 되어 끊긴 적 없는 캐럴에게 «연결이 끊긴 사이의 변경을
 * 놓쳐…»가 선다.
 *
 * **막는 것은 둘이다.** 하나가 이것 — id 가 재기동을 넘어 겹치지 않고 순번으로 짐작되지 않는다. 다른 하나는
 * 방송이 제외 대상을 **요청과 같은 세션일 때만** 빼는 것이다(`broadcast.ts`의 `sentBy`). 둘째만으로는 남의
 * 연결은 안 빠지지만 **같은 세션의 새 연결**이 옛 id 를 받는 길이 남는다 — 재기동 뒤 같은 사람이 새로 연
 * 셸이 작은 번호부터 받다가 그 값에 닿으면, 옛 셸이 낸 게시의 방송에서 **새 셸이** 빠진다(응답의 `markerOps`
 * 는 옛 셸의 스토어에 얹힌다). 무작위 id 는 그 길을 닫는다.
 *
 * `crypto.randomUUID()`는 122비트다 — 겹칠 걱정은 셈에 넣지 않는다. 로그에서는 카운터처럼 순서를 읽을 수
 * 없다(그것이 대가다).
 */
import { randomUUID } from 'node:crypto'

export function nextConnectionId(): string {
  return `wsc_${randomUUID()}`
}
